// Package i18n выбирает язык пользовательского вывода senso и хранит пары
// перевода. Каталога с ключами намеренно нет: перевод пишется прямо в месте
// использования парой аргументов (en, ru), поэтому строку невозможно
// потерять при переименовании ключа, а её текст виден в коде рядом с логикой.
package i18n

import (
	"fmt"
	"strings"
	"sync/atomic"
)

// Lang - язык пользовательского вывода.
type Lang int

const (
	// EN - английский, язык по умолчанию.
	EN Lang = iota
	// RU - русский, включается только явной настройкой локали.
	RU
)

// String возвращает код языка ("en" или "ru").
func (l Lang) String() string {
	if l == RU {
		return "ru"
	}
	return "en"
}

// current хранит выбранный язык. atomic нужен, потому что вывод может
// печататься из нескольких горутин индексации, а язык при этом только
// читается после единственной установки на старте.
var current atomic.Int32

// envVars - переменные окружения в порядке убывания приоритета.
// SENSO_LANG стоит первой и перекрывает системную локаль: она нужна, чтобы
// принудительно получить английский вывод на русской машине (и наоборот),
// а также чтобы тесты не зависели от локали машины разработчика.
var envVars = []string{"SENSO_LANG", "LC_ALL", "LC_MESSAGES", "LANG"}

// Detect определяет язык по переменным окружения, читая их через getenv.
// Первая непустая переменная решает исход: если её значение начинается с
// "ru" (без учёта регистра), выбирается русский, иначе английский. Значения
// "C" и "POSIX" трактуются как английский, как это принято для локалей.
// Когда ни одна переменная не задана, возвращается EN.
func Detect(getenv func(string) string) Lang {
	for _, name := range envVars {
		v := strings.TrimSpace(getenv(name))
		if v == "" {
			continue
		}
		if strings.HasPrefix(strings.ToLower(v), "ru") {
			return RU
		}
		return EN
	}
	return EN
}

// Set устанавливает язык вывода. Вызывается один раз на старте из main.
func Set(l Lang) {
	current.Store(int32(l))
}

// Current возвращает текущий язык вывода.
func Current() Lang {
	return Lang(current.Load())
}

// T возвращает ru при русском языке вывода и en во всех остальных случаях.
func T(en, ru string) string {
	if Current() == RU {
		return ru
	}
	return en
}

// Tf форматирует ту из строк en/ru, которая соответствует текущему языку.
// Обе строки обязаны иметь одинаковый набор глаголов формата и одинаковый
// порядок аргументов.
//
// Для создания ошибок Tf использовать нельзя, если сообщение оборачивает
// другую ошибку: Tf возвращает уже готовую строку, и глагол %w потерял бы
// смысл, разорвав цепочку errors.Is/errors.As. В таких местах язык нужно
// выбирать через T, а форматирование оставлять за fmt.Errorf:
//
//	fmt.Errorf(i18n.T("cannot open database: %w", "не удалось открыть базу: %w"), err)
func Tf(en, ru string, a ...any) string {
	return fmt.Sprintf(T(en, ru), a...)
}
